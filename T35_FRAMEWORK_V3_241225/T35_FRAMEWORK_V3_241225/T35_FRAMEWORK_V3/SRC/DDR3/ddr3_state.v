//check_err

always @ (posedge clk )begin
	if(DDR_CTRL_RVALID_0)begin
		RdCheckBit <= ~RdCheckBit;
	end else begin 
		RdCheckBit <= RdCheckBit;
	end 
end 
//WrCheckBit

always @(posedge clk)begin
	if(C_STATE==INIT_CHECK&&(DDR_CTRL_RDATA_0[63:0]!={64{RdCheckBit}}))begin  //DDR_CTRL_RVALID_0
			
		check_err1<=DDR_CTRL_RVALID_0;
			
	end else begin 
		check_err1 <=0;
	end 
end 
//check_err1

