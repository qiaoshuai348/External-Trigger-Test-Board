		ddr_verify_st<=ddr_verify_st;
	end 
end 
//ddr_verify_st
always @(posedge clk )begin
	if(ddr_verify_st==1&&DDR_CTRL_RVALID_0==1&&DDR_CTRL_RDATA_0[15:0]<65533)begin
			if(DDR_CTRL_RDATA_0[15:0]-DDR_CTRL_RDATA_0[79:64]==1'b1)begin
				ddr_verify_err<=1'b0;
			end else begin 
				ddr_verify_err<=1'b1;
			end 
	end else begin 
		ddr_verify_err <= 1'b0;
	end 
end 
//ddr_verify_err


always @(posedge clk )begin
	if (cnt1s[26]==1&&cnt1s[25]==1)begin //100ms
			s1_flag<=1;
	end else begin 
			s1_flag<=0;
	end 
end 
//s1_flag

always @ (posedge clk )begin
	
	if (s1_flag)begin //100ms
		cnt1s<=0;
	end else  begin 
		cnt1s<=cnt1s+1;
	end 
	
end 
//cnt100ms



always @ (posedge clk )begin 
	if(s1_flag)begin 
		data_num_wr<=0;
	end else  if(DDR_CTRL_WREADY_0&DDR_CTRL_WVALID_0)begin
		data_num_wr<=data_num_wr+1;
	end else begin 
		data_num_wr<=data_num_wr;
	end 
end 
//data_num_wr//128bit


always @ (posedge clk )begin 
	if(s1_flag)begin 
		data_num_rd<=0;
	end else  if(DDR_CTRL_RVALID_0)begin
		data_num_rd<=data_num_rd+1;
	end else begin 
		data_num_rd<=data_num_rd;
	end 
end 
//data_num_wr//128bit


always @(posedge clk)begin
	if(reset_done_t1==0)begin 
		checkerr_cnt <= 0;
	end else if(check_err)begin 
		checkerr_cnt<=checkerr_cnt+1'b1;
	end else begin 
		checkerr_cnt <=checkerr_cnt;
	end 
end 
//checkerr_cnt

always @(posedge clk)begin 
	if(reset_done_t1==0||(DDR_CTRL_RLAST_0==1&DDR_CTRL_RVALID_0==1)||(C_STATE==INIT_DONE))begin
		rd_cnt <= 0;
	end else if(DDR_CTRL_RVALID_0)begin
		rd_cnt <= rd_cnt + 1 ;
	end else begin 
		rd_cnt <= rd_cnt;
	end 
end 
//rd_cnt


  always @( posedge clk)
  begin
  if(C_STATE==STATE_READ&&DDR_CTRL_RVALID_0==0)  DataRdTimeOut <=  DataRdTimeOut - {7'h0, (|DataRdTimeOut)};
  else DataRdTimeOut <= 8'hff;
  end

  always @( posedge clk)  DataRdReadyClr <=  (DataRdTimeOut == 5'h1);
  
  always @(posedge clk )  begin 
  	if(ddr_state_rst_t1) DataRdTimeOut_flag<=0;
  	else if(DataRdReadyClr) DataRdTimeOut_flag<=1;
  	else  DataRdTimeOut_flag <=DataRdTimeOut_flag;
  end 
`endif

//****************************DDR STATE *******************************************************************
always @(posedge clk)begin 
	if( slip_check_d==1 )begin //reset all//  |DataRdReadyClr==1
		C_STATE<=INIT_DONE;
	end else if(reset_done_t1==0 )begin//DDR RESET 
		C_STATE<=IDLE;
	end else if((DDR_CLG_R_T1==1&&C_STATE==PRE_WRRTE)||(DDR_CLG_R_T1==1&&C_STATE==PRE_READ))begin//DDR CLEAR
		C_STATE<=INIT_DONE;
	end else begin 
		C_STATE<=N_STATE;
	end 
end 
//C_STATE	


always @( * ) begin //*
	case(C_STATE)
	IDLE:	begin//0
				if(DDR_CTRL_AREADY_0)begin 
					N_STATE<=INIT_WRITE;
				end else begin 
					N_STATE<=IDLE;
				end 
	end 
	
	INIT_WRITE:begin //1
				if(init_wrdone)begin 
					N_STATE<=INIT_CHECK;
				end else begin 
					N_STATE<=INIT_WRITE;
				end 
	end 
	
	INIT_CHECK:begin //2
				if(init_done_flag==1)begin//&&(check_fail==0) //init_done_flag =1 //check_done==1
					N_STATE<=INIT_DONE;
				end else begin 
					N_STATE<=INIT_CHECK;
				end 
	end 
	
	INIT_DONE:begin//3
				if(DDR_CTRL_AREADY_0)begin 
					N_STATE<=PRE_WRRTE;
				end else begin 
					N_STATE<=INIT_DONE;
				end 
	end 
	
	PRE_WRRTE:begin //4
				if(ddr_alfull==1)begin//if ddr full ,jump to read  //&&wr_cycle==0
					N_STATE<=PRE_READ;
				end else if (wrfifo_count<(`ALEN_0+1)&&wrfifo_full==0)begin //if write fifo do not have data;jump to read //wrfifo_pflag==0
					N_STATE<=PRE_READ;
				end else begin 
					N_STATE<=STATE_WRRTE;
				end 
		
	end 
	
	STATE_WRRTE:begin//5
				if (DDR_CTRL_WLAST_0&DDR_CTRL_WREADY_0)begin //if write cycle done,jump to read //DDR_CTRL_BVALID_0 //DDR_CTRL_WLAST_0
					N_STATE<=PRE_READ;
				end else begin 
					N_STATE<=STATE_WRRTE;
				end 
	end 
	PRE_READ:begin //6
				if(ddr_alempty==1)begin //if ddr empty ,jump to write  
					N_STATE<=PRE_WRRTE;
				end else if(rdfifo_count>RDFIFO_COUNT_END||rdfifo_full==1)begin // if read fifo have a lot of data ;jumo to  write //rdfifo_pflag==1
					N_STATE<=PRE_WRRTE;				
				end else begin
					N_STATE<=STATE_READ;
				end 
		
	end 
	
	STATE_READ:begin //7
			    if (ddrctrl_avalid_rd)begin//if read cycle done ,jump to write ddrctrl_avalid_rd //DDR_CTRL_RLAST_0&&DDR_CTRL_RVALID_0
					N_STATE<=PRE_WRRTE;
				end else begin 
					N_STATE<=STATE_READ;
				end 
	end 
	
	default:begin 
		N_STATE<=IDLE;
	end 
	
	endcase
end 





