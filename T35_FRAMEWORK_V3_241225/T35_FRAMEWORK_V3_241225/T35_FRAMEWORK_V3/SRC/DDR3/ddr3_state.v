//end 



always @ (posedge clk )begin
	if(wrfifo_rden)begin
		WrCheckBit <= ~WrCheckBit;
	end else begin 
		WrCheckBit <= WrCheckBit;
	end 
end 
//WrCheckBit
		
always @(posedge clk)begin
	if(C_STATE==INIT_WRITE&&DDR_CTRL_WREADY_0==1)begin		
		DDR_CTRL_WDATA_0[63:0]<={64{WrCheckBit}};	
	end else if (DDR_CTRL_WREADY_0)begin 
		DDR_CTRL_WDATA_0 <=wrfifo_rdata;
	end else begin 
		DDR_CTRL_WDATA_0 <=DDR_CTRL_WDATA_0;
	end 
end 

//DDR_CTRL_WDATA_0 <=wrfifo_rdata;


//*************************************read /init check*****************************************************
always @(posedge clk)begin 
	if(ddr_state_rst_t1)begin 
		rd_addr <= `START_ADDR_0;
	end else if(C_STATE==INIT_DONE)begin
		rd_addr <=0;
	end else if(DDR_CTRL_AVALID_0==1&DDR_CTRL_ATYPE_0==0)begin 
		rd_addr <= rd_addr+ADDR_OFFSET;
	end else begin 
		rd_addr <= rd_addr ;
	end 
end 
//rd_addr




always @(posedge clk)begin 
	if(reset_done_t1==0||ddrctrl_avalid_rd==1||C_STATE==INIT_DONE)begin
		rd_cycle <= 0;
	end else if((C_STATE==STATE_READ)||(C_STATE==INIT_CHECK&&check_done==0))begin		
		rd_cycle <= 1;		
	end else begin 
		rd_cycle <= rd_cycle;
	end 
end 

//rd_cycle


always @ (posedge clk )begin 
	if(reset_done_t1==0)begin 
		ddrctrl_avalid_rd<=0;
	end else if(ddrctrl_avalid_rd==0&&rd_cycle==1&&DDR_CTRL_AREADY_0==1)begin//&&C_STATE==STATE_READ
		ddrctrl_avalid_rd<=1;
	end else begin 
		ddrctrl_avalid_rd<=0;
	end 
end 
//ddrctrl_avalid_rd



