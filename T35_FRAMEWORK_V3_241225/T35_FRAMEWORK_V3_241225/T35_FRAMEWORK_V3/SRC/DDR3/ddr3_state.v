module ddr3_state
		(

		input	wire						clk					,
		input	wire						reset_done			,
		input	wire						DDR_CLG_R			,
		input	wire						ddrpll_locked		,
		input	wire						skip_check			,
		                        			
		input	wire						wr_clk				,
		input	wire	[63:0]				wrddr3_data			,
		input	wire						wrddr3_en			,
		input	wire						rd_clk				,
		input	wire						rddr3_en			,//
		input	wire						fx3_full			,	
		input   wire    [`DDR3ADDRE_MAXBIT:0]	threshold_num		,//unit: byte			
		output	wire	[63:0]				rddr3_data			,
		output	reg							rddr3_vld=0			,
		
		//ddr3 state signals		
		output	reg		[`DDR3ADDRE_MAXBIT:0]	rema_num			,//unit:byte £¬set it to 256bit
		//output	reg							ddr_pfull		=0	,//ddr programme full;if it goes high;ddr can receive only one frame data.
		output  wire     [7:0]				ddr_code		    , // ddrcoe [3:0]==0  {1'b0,1'b0,ddr_pfull,ddr_alempty,ddr_alfull,addr_err,check_fail,init_done_flag};//init_done_flag //check_done_t2
		//ddr axi signals			
		input 								DDR_CTRL_AREADY_0	,  //**Address ready.
  		input [7:0] 						DDR_CTRL_BID_0		,  //not use 
  		input 								DDR_CTRL_BVALID_0	,  //Write response valid. This signal indicates that the channel is signaling a valid write response.                  
  		input [127:0] 						DDR_CTRL_RDATA_0	,  //**Read data.              
  		input [7:0] 						DDR_CTRL_RID_0		,  //Read ID tag. This signal is the identification tag for the read data group of signals generated by the slave. not user                                                                                                                    
  		input 								DDR_CTRL_RLAST_0	,  //**Read last. This signal indicates the last transfer in a read burst.                      
  		input [1:0] 						DDR_CTRL_RRESP_0	,  //Read response. This signal indicates the status of the read transfer
  		input 								DDR_CTRL_RVALID_0	,  //**Read valid
  		input 								DDR_CTRL_WREADY_0	,  //**Write ready. This signal indicates that the slave can accept the write data.
  		                		                                                                                          
  		output reg[31:0] 					DDR_CTRL_AADDR_0	,  //** Address. ATYPE defines whether it is a read or write address. It gives the address of the first transfer in a burst transaction. 
  		output [1:0] 						DDR_CTRL_ABURST_0	,  // Burst type. The burst type and the size determine how the address  for each transfer within the burst is calculated.               
  		output [7:0] 						DDR_CTRL_AID_0		,  // Address ID. This signal identifies the group of address signals. Depends on ATYPE, the ID can be for a read or write address group             
  		output [7:0] 						DDR_CTRL_ALEN_0		,  // Burst length. This signal indicates the number of transfers in a burst
  		output [1:0] 						DDR_CTRL_ALOCK_0	,  // Lock type. This signal provides additional information about the  atomic characteristics of the transfer  
  		output [2:0] 						DDR_CTRL_ASIZE_0	,  // Burst size. This signal indicates the size of each transfer in the burst.                       
  		output reg							DDR_CTRL_ATYPE_0	,  //** This signal distinguishes whether is it is a read or write operation. 0= read and 1 = write.
  		output 								DDR_CTRL_AVALID_0	,  //** Address valid. This signal indicates that the channel is signaling valid address and control information.                                                
  		output 								DDR_CTRL_BREADY_0	,  // Response ready. This signal indicates that the master can accept a write response                            
  		output 								DDR_CTRL_RREADY_0	,  //** Read ready. This signal indicates that the master can accept the read data and response information.                                              
  		output reg	[127:0] 				DDR_CTRL_WDATA_0    ,  //** Write data.
  		output [7:0] 						DDR_CTRL_WID_0		,  // Write ID tag. This signal is the ID tag of the write data transfer
  		output 	reg							DDR_CTRL_WLAST_0	,  //** Write last. This signal indicates the last transfer in a write burst
  		output [15:0] 						DDR_CTRL_WSTRB_0	,  // Write strobes. This signal indicates which byte lanes hold valid data. There is one write strobe bit for each eight bits of the write data bus  
  		output 	reg							DDR_CTRL_WVALID_0      //** Writ

);

localparam ASIZE_0 =3'B100;//a burst is 16 bytes
localparam ADDR_OFFSET = ((`ALEN_0)<<ASIZE_0) ;//ADDR_OFFSET = (ALEN + 1)*32;       
localparam STOP_ADDR = `STOP_ADDR_0 ;//`STOP_ADDR_0 - ADDR_OFFSET-4;	
localparam RDFIFO_COUNT_END = (`ALEN_0*4);//(`RDFIFI_MAX)-(`ALEN_0*2);//
//localparam COUNT_END = log2(RDFIFI_MAX);                
                 
                 
localparam 
		IDLE 			=3'B000,
		INIT_WRITE		=3'B001,
		INIT_CHECK		=3'B010,
		INIT_DONE		=3'B011,
		PRE_WRRTE		=3'B100,//4
		STATE_WRRTE		=3'B101,//5
		PRE_READ		=3'B110,//6
		STATE_READ		=3'B111;//7
	
	

		reg	[2:0]			C_STATE	=0		;
		reg [2:0] 			N_STATE	=0		;
		                	            	
	          	
		wire				wrfifo_full		;
		wire				rdfifo_full		;
	
		//

		wire					rdfifo_empty		;
        reg						ddr_pfull	=0		;
		reg	 [55:0]				wr_addr			=`START_ADDR_0;
		reg  [55:0]				rd_addr			=0	;  
		reg  [55:0]				rema_num_temp	=0	;     		
		wire 					wrfifo_rden			;
		reg 					wrfifo_rdreq	=0	;
		wire [127:0]			wrfifo_rdata  		;   
		wire [`COUNT_ENDBIT:0]				wrfifo_count  		;//how many 128bit
		                    	                	
		wire [`COUNT_ENDBIT:0]				rdfifo_count  		;//how many 128bit
		reg 					rdfifo_rden 	=0	;
                            	
		reg						init_wrdone		=0  ;	
		reg						check_err		=0	;//rise one clock
		reg						wr_cycle		=0	;
		reg						wr_cycle_t0		=0	;
		reg						rd_cycle		=0	;

		reg 					addr_err		=0	;// When the read address is greater than the write address;it will goes high          
		reg						check_done		=0  ;//  
		reg 					check_done_t0	=0	;
		reg 					check_done_t1	=0	;
		reg						check_done_t2	=0	;                                                                                  
						
		reg 					check_fail		=0  ;//if check have error,check_fail is always 1                                          
		reg						ddr_alfull		=0  ;//ddr almost full,ddr won't write any more data. If it goes  high,  will lose data.   
		reg						ddr_alempty		=0  ;//ddr almost empty ,                                                                  
				    		
		reg						ddr_state_rst	=0	;
		reg						ddr_state_rst_t1=0	;
		reg						reset_done_t0	=0	;
		reg						reset_done_t1	=0	;
		                		                  	
		reg 					DDR_CLG_R_T0	=0	;
		reg						DDR_CLG_R_T1	=0	;
		
		reg 					DDR_CTRL_WLAST_1 = 0; 
		wire 					DDR_CTRL_WLAST_2 	;
		reg  [7:0]				wr_cnt			=0	;

		reg 					ddrctrl_avalid_rd =0;//DDR_CTRL_AVALID_RD
		reg 						init_done_flag	=0;
		reg [`DDR3ADDRE_MAXBIT:0]	check_addr		=0;  
		reg [2:0]				skip_check_t		=0; 
		reg  					slip_check_d		=0;
		reg 					WrCheckBit			=0;
		reg 					RdCheckBit			=0;
		reg 					check_err1 			=0;
		reg 					check_err2	 		=0;

assign DDR_CTRL_AID_0=8'h00;
assign DDR_CTRL_ALOCK_0=2'b00;
assign DDR_CTRL_WID_0=8'h00;
assign DDR_CTRL_WSTRB_0=32'hFFFFFFFF;
assign DDR_CTRL_ABURST_0=2'b01;
assign DDR_CTRL_ASIZE_0=ASIZE_0;//a burst is 16 bytes
assign DDR_CTRL_ALEN_0=`ALEN_0-1;// burst times 
assign DDR_CTRL_BREADY_0=1'b1;
assign DDR_CTRL_RREADY_0=1'b1;
 
assign ddr_code = {1'b0,1'b0,ddr_pfull,ddr_alempty,ddr_alfull,addr_err,check_fail,init_done_flag};//init_done_flag //check_done_t2
assign DDR_CTRL_AVALID_0 = (wr_cycle==1&wr_cycle_t0==0)|(ddrctrl_avalid_rd==1);//(rd_cycle==1&rd_cycle_t0==0);
//DDR_CTRL_AVALID_0

initial begin
	check_done  <= 0;
	init_wrdone <= 0;
end 
always @(posedge clk )begin 
	
	ddr_state_rst<= (~reset_done)|(DDR_CLG_R==1)|(~ddrpll_locked);
	ddr_state_rst_t1<=ddr_state_rst;
	//
	
	reset_done_t0<=reset_done;
	reset_done_t1<=reset_done_t0;
	
	DDR_CLG_R_T0<=DDR_CLG_R;
		
	wr_cycle_t0 <= wr_cycle;
	//rd_cycle_t0 <= rd_cycle;
	
	check_done_t0<=check_done;
	check_done_t1<=check_done_t0;
	check_done_t2<=check_done_t1; 
	
	
	skip_check_t<={skip_check_t[1:0],skip_check};
	   
	
end 

always @ (posedge clk )begin 
	if(skip_check==1||skip_check_t>0)begin
		slip_check_d<=1;
	end else if (reset_done_t1==1)begin
		slip_check_d<=0;
	end else begin
		slip_check_d<=slip_check_d;
	end 
end 
//assign slip_check_d=(|skip_check_t) |  skip_check ;

always @ (posedge clk)begin
	if(ddr_state_rst_t1)begin 
		addr_err<=0;
	end else if(wr_addr<rd_addr)begin
		addr_err<=1;
	end else begin
		addr_err<=addr_err;
	end 
end 	
//addr_err

always @(posedge clk )begin 
	if(reset_done_t1==0)begin		
		init_wrdone<=0;
	end else if(C_STATE == INIT_DONE)begin
		init_wrdone<=1;
	end else if(C_STATE==INIT_WRITE&&wr_addr[`DDR3ADDRE_MAXBIT:0]>(STOP_ADDR-1))begin//DDR_CTRL_BVALID_0  DDR_CTRL_WLAST_0==1
		init_wrdone<=1;
	end else begin 
		init_wrdone<=init_wrdone;
	end 
end 
//init_wrdone


//

always @ (posedge clk )begin 
	if(reset_done_t1==0)begin 
		check_addr<=0;
	end else if (C_STATE==INIT_CHECK&&DDR_CTRL_RLAST_0==1&&DDR_CTRL_RVALID_0==1)begin
		check_addr <= check_addr+ADDR_OFFSET;
	end else begin 
		check_addr <= check_addr;
	end 
end 
//check_addr

always @(posedge clk )begin 
	if(reset_done_t1==0)begin	
		init_done_flag<=0;
	end else if(C_STATE == INIT_DONE)begin
		init_done_flag<=1;
	end else if(check_addr[`DDR3ADDRE_MAXBIT:0]>(STOP_ADDR-1-(ADDR_OFFSET<<1))&&DDR_CTRL_RLAST_0==1&&DDR_CTRL_RVALID_0==1)begin
		init_done_flag<=1;
	end else begin 
		init_done_flag<=init_done_flag;
	end 
end 
//init_done_flag

//
always @(posedge clk )begin 
	if(reset_done_t1==0)begin	
		check_done<=0;
	end else if(C_STATE == INIT_DONE)begin
		check_done<=1;
	end else if(C_STATE==INIT_CHECK&&rd_addr[`DDR3ADDRE_MAXBIT:0]>(STOP_ADDR-(ADDR_OFFSET<<1)-1))begin//&&DDR_CTRL_RLAST_0==1&&DDR_CTRL_RVALID_0==1
		check_done<=1;
	end else begin 
		check_done<=check_done;
	end 
end 
//check_done

always @(posedge clk )begin 
	if(C_STATE==INIT_DONE|reset_done_t1==0)begin 
		DDR_CLG_R_T1<=0;
	end else if (DDR_CLG_R_T0==0&&DDR_CLG_R==1&&C_STATE>3'b010)begin 
		DDR_CLG_R_T1<=1;
	end else begin 
		DDR_CLG_R_T1<=DDR_CLG_R_T1;
	end 
end 
//DDR_CLG_R_T1


always @(posedge clk)begin 
	if(wr_addr<rd_addr)begin 
		rema_num_temp<=0;
	end else begin
		rema_num_temp<= wr_addr-rd_addr;
	end 
end 
///rema_num_temp

always @(posedge clk)begin 
	
		rema_num<=rema_num_temp[`DDR3ADDRE_MAXBIT:0];
end 
//rema_num

always @(posedge clk)begin 
	if(rema_num<(ADDR_OFFSET<<1))begin 
		ddr_alempty<=1;
	end else begin 
		ddr_alempty<=0;
	end 
end 
//ddr_alempty

always @(posedge clk)begin
	if(rema_num>(`DDR3ADDRE_MAX-(ADDR_OFFSET<<1)))begin // //((STOP_ADDR-rema_num)<(ADDR_OFFSET<<2))
		ddr_alfull<=init_wrdone;//1
	end else begin 
		ddr_alfull<=0;
	end 
end 
//ddr_alfull

always @(posedge clk)begin
	if(rema_num>threshold_num)begin 
		ddr_pfull<=init_wrdone;//1
	end else begin
		ddr_pfull<=0;
	end 
end 
//ddr_pfull ddr programme full;if it goes high;ddr can receive only one frame data.

always @(posedge clk)begin 
	if(ddr_state_rst_t1)begin 
		wr_addr <= `START_ADDR_0;
	end else if(C_STATE==INIT_DONE)begin
		wr_addr <=0;//ADDR_OFFSET
	end else if(DDR_CTRL_AVALID_0&DDR_CTRL_ATYPE_0)begin 
		wr_addr <= wr_addr+ADDR_OFFSET;
	end else begin 
		wr_addr <= wr_addr ;
	end 
end 
//wr_addr

always @(posedge clk )begin 
	if(C_STATE == INIT_WRITE||C_STATE==PRE_WRRTE||C_STATE==STATE_WRRTE)begin 
		 DDR_CTRL_ATYPE_0<=1'b1;
		 DDR_CTRL_AADDR_0<=wr_addr[`DDR3ADDRE_MAXBIT:0];
	end else begin 
		 DDR_CTRL_ATYPE_0<=0;   
		 DDR_CTRL_AADDR_0<=rd_addr[`DDR3ADDRE_MAXBIT:0];     
	end 
end 
//DDR_CTRL_ATYPE_0 DDR_CTRL_AADDR_0  

always @(posedge clk)begin 
	if(reset_done_t1==0|(DDR_CTRL_WLAST_0==1&DDR_CTRL_WREADY_0==1))begin//DDR_CTRL_BVALID_0  //reset_done_t1==0|DDR_CTRL_WLAST_0==1
		wr_cycle <= 0;
	end else if((C_STATE==STATE_WRRTE&&DDR_CTRL_AREADY_0==1)||(C_STATE==INIT_WRITE&&DDR_CTRL_AREADY_0==1&&init_wrdone==0))begin		
		wr_cycle <= 1;		
	end else begin 
		wr_cycle <= wr_cycle;
	end 
end 
//wr_cycle

always @(posedge clk)begin
	 if(wr_cycle)begin
	 	if(wrfifo_rden)begin
			wr_cnt <= wr_cnt+1;		
		end else begin 
			wr_cnt <= wr_cnt;
		end 
	end else begin 
		wr_cnt <= 0;
	end 
end 
//wr_cnt

always @(posedge clk)begin
	if(!reset_done_t1)begin 
		wrfifo_rdreq <= 0;
	end else if((wr_cnt>=`ALEN_0-1)&&DDR_CTRL_WREADY_0==1)begin
		wrfifo_rdreq <= 0;
	end else if(wr_cycle&&DDR_CTRL_AVALID_0)begin/// (wr_cycle)
		wrfifo_rdreq<=1;
	end else begin 
		wrfifo_rdreq <= wrfifo_rdreq;
	end 
end 
//wrfifo_rdreq	


assign wrfifo_rden=wrfifo_rdreq&DDR_CTRL_WREADY_0;
//wrfifo_rden

always @(posedge clk)begin
	if((wr_cnt==(`ALEN_0)&&DDR_CTRL_WREADY_0==1)||(reset_done_t1==0))begin
		DDR_CTRL_WLAST_0<=0;
	end else if(wr_cnt==(`ALEN_0-1)&&wrfifo_rden==1)begin 
		DDR_CTRL_WLAST_0<=1;
	end else begin 
		DDR_CTRL_WLAST_0<=DDR_CTRL_WLAST_0;
	end 
//	DDR_CTRL_WLAST_0 <= (wr_cnt==(`ALEN_0-1)&&wrfifo_rden==1);
end 


always @(posedge clk)begin
   if((DDR_CTRL_WLAST_0==1&DDR_CTRL_WREADY_0==1)|reset_done_t1==0)begin
		DDR_CTRL_WVALID_0<=1'b0;
	end else if(wrfifo_rden)begin
		DDR_CTRL_WVALID_0<=1'b1;		
	end else begin 
		DDR_CTRL_WVALID_0<=DDR_CTRL_WVALID_0;
	end 
end 

//DDR_CTRL_WVALID_0 

