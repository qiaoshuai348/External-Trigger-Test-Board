reg [7:0] 					DataRdTimeOut   = 8'hff ;
reg       					DataRdReadyClr  = 1'h0  ;
reg 						DataRdTimeOut_flag =0   ;

always @ (posedge clk )begin
	if(ddr_state_rst_t1)begin
		ddr_verify_st <= 1'b0;
	end else if(DDR_CTRL_RVALID_0)begin
		ddr_verify_st <=1'b1;
