//end
////check_err2

always @ (posedge clk )begin
	check_err <= check_err1;//|check_err2;
end  
//check_err

always @(posedge clk )begin 
	if(reset_done_t1==0)begin
		check_fail<=0;
	end else if(check_err)begin 
		check_fail<=1;
	end else begin 
		check_fail <= check_fail;
	end
end 
//check_fail;


//

  
  
//************rd_clk**********************

always @(posedge rd_clk)begin 
	if(rdfifo_empty==0&fx3_full==0&rddr3_en==1)begin		
		rdfifo_rden<=1;
	end else begin 
		rdfifo_rden<=0;
	end 
end 
//rdfifo_rden

always@ (posedge rd_clk)begin 
	rddr3_vld <= rdfifo_empty==0&rdfifo_rden==1;
end 
//rddr3_vld

//************************************test  ************************************************************

`ifdef DDRTEST_BW

reg [`DDR3ADDRE_MAXBIT:0]	checkerr_cnt	=0;   
reg 	   					ddr_verify_err	=0;
reg 	   					ddr_verify_st	=0;

reg [26:0] 					cnt1s 		    =0;
reg [31:0] 					data_num_wr		=0;
reg [31:0] 					data_num_rd 	=0;	
